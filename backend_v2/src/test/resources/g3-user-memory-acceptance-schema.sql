CREATE EXTENSION IF NOT EXISTS vector;

CREATE TABLE jchatmind_user (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account VARCHAR(128) NOT NULL UNIQUE,
    username VARCHAR(128) NOT NULL,
    password VARCHAR(128) NOT NULL,
    gender SMALLINT,
    birthday DATE,
    avatar_url TEXT,
    email VARCHAR(255),
    school VARCHAR(255),
    signature TEXT,
    is_banned SMALLINT NOT NULL DEFAULT 0,
    is_admin SMALLINT NOT NULL DEFAULT 0,
    last_login_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE agent (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id BIGINT NOT NULL REFERENCES jchatmind_user(user_id) ON DELETE CASCADE,
    name TEXT NOT NULL,
    description TEXT,
    system_prompt TEXT,
    model TEXT NOT NULL,
    allowed_tools JSONB NOT NULL DEFAULT '[]'::jsonb,
    chat_options JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE chat_session (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id TEXT NOT NULL,
    agent_id UUID REFERENCES agent(id) ON DELETE SET NULL,
    title TEXT,
    metadata JSONB,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE chat_message (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    session_id UUID NOT NULL REFERENCES chat_session(id) ON DELETE CASCADE,
    role VARCHAR(32) NOT NULL,
    content TEXT NOT NULL,
    metadata JSONB,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE agent_execution_session_sequence (
    session_id UUID PRIMARY KEY REFERENCES chat_session(id) ON DELETE CASCADE,
    next_sequence BIGINT NOT NULL CHECK (next_sequence >= 1)
);

CREATE TABLE agent_execution_turn_message (
    chat_message_id UUID PRIMARY KEY REFERENCES chat_message(id) ON DELETE CASCADE,
    session_id UUID NOT NULL REFERENCES chat_session(id) ON DELETE CASCADE,
    sequence_no BIGINT NOT NULL CHECK (sequence_no >= 0)
);

CREATE INDEX idx_g3_agent_turn_session_sequence
    ON agent_execution_turn_message(session_id, sequence_no, chat_message_id);

CREATE TABLE agent_execution_task (
    id UUID PRIMARY KEY,
    session_id UUID NOT NULL REFERENCES chat_session(id) ON DELETE CASCADE,
    user_id TEXT NOT NULL,
    agent_id TEXT NOT NULL,
    user_message_id UUID NOT NULL REFERENCES chat_message(id) ON DELETE CASCADE,
    sequence_no BIGINT NOT NULL CHECK (sequence_no >= 0),
    status TEXT NOT NULL DEFAULT 'PENDING'
        CHECK (status IN ('PENDING', 'RUNNING', 'COMPLETED', 'FAILED')),
    attempt_count INTEGER NOT NULL DEFAULT 0 CHECK (attempt_count >= 0),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    started_at TIMESTAMP,
    completed_at TIMESTAMP,
    failure_type TEXT,
    UNIQUE (session_id, sequence_no)
);

CREATE INDEX idx_g3_agent_task_runnable
    ON agent_execution_task(created_at, id)
    WHERE status IN ('PENDING', 'RUNNING');

CREATE INDEX idx_g3_agent_task_session_sequence
    ON agent_execution_task(session_id, sequence_no)
    WHERE status IN ('PENDING', 'RUNNING');

CREATE TABLE knowledge_base (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    name TEXT NOT NULL,
    description TEXT,
    metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
    owner_id BIGINT NOT NULL REFERENCES jchatmind_user(user_id) ON DELETE CASCADE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE agent_knowledge_base (
    agent_id UUID NOT NULL REFERENCES agent(id) ON DELETE CASCADE,
    kb_id UUID NOT NULL REFERENCES knowledge_base(id) ON DELETE CASCADE,
    bound_by_user_id BIGINT,
    bound_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (agent_id, kb_id)
);

CREATE TABLE user_memory (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id VARCHAR(64) NOT NULL,
    session_id UUID REFERENCES chat_session(id) ON DELETE SET NULL,
    memory_type VARCHAR(32) NOT NULL,
    content TEXT NOT NULL,
    importance VARCHAR(16) NOT NULL DEFAULT 'medium',
    evidence_message_id UUID,
    evidence_text TEXT,
    superseded_by_memory_id UUID REFERENCES user_memory(id) ON DELETE CASCADE,
    expires_at TIMESTAMP,
    embedding VECTOR(1024),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_g3_user_memory_user_id ON user_memory(user_id);

CREATE TABLE user_memory_candidate (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id VARCHAR(64) NOT NULL,
    session_id UUID NOT NULL REFERENCES chat_session(id) ON DELETE CASCADE,
    memory_type VARCHAR(32) NOT NULL,
    content TEXT NOT NULL,
    evidence TEXT,
    importance VARCHAR(16) NOT NULL DEFAULT 'medium',
    evidence_message_id UUID,
    status VARCHAR(16) NOT NULL DEFAULT 'PENDING'
        CHECK (status IN ('PENDING', 'PERSISTED', 'DISCARDED')),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_g3_user_memory_candidate_user_id ON user_memory_candidate(user_id);

CREATE UNIQUE INDEX user_memory_candidate_idempotency_uq
    ON user_memory_candidate(user_id, memory_type, evidence_message_id, content)
    WHERE evidence_message_id IS NOT NULL;

CREATE TABLE user_memory_automation_settings (
    user_id VARCHAR(64) PRIMARY KEY,
    automation_mode VARCHAR(16) NOT NULL DEFAULT 'BALANCED'
        CHECK (automation_mode IN ('REVIEW_ALL', 'BALANCED', 'AUTOMATIC')),
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE user_memory_extraction_state (
    session_id UUID PRIMARY KEY REFERENCES chat_session(id) ON DELETE CASCADE,
    user_id VARCHAR(64) NOT NULL,
    last_extracted_user_message_count INTEGER NOT NULL DEFAULT 0,
    last_attempt_at TIMESTAMP,
    last_success_at TIMESTAMP,
    last_failure_type VARCHAR(80),
    failure_count INTEGER NOT NULL DEFAULT 0,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE user_memory_consolidation_proposal (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id VARCHAR(64) NOT NULL,
    source_memory_ids JSONB NOT NULL,
    source_fingerprint VARCHAR(64) NOT NULL,
    proposed_type VARCHAR(32) NOT NULL,
    proposed_content VARCHAR(300) NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'PENDING'
        CHECK (status IN ('PENDING', 'APPLIED', 'DISCARDED', 'STALE')),
    applied_memory_id UUID,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX user_memory_consolidation_pending_idx
    ON user_memory_consolidation_proposal(user_id, created_at DESC)
    WHERE status = 'PENDING';
