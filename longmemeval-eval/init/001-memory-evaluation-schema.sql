BEGIN;

-- This schema is only for the dedicated longmemeval_eval database.
CREATE EXTENSION IF NOT EXISTS vector;

CREATE TABLE IF NOT EXISTS public.jchatmind_user (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY
);

CREATE TABLE IF NOT EXISTS public.chat_session (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id TEXT NOT NULL,
    agent_id UUID,
    title VARCHAR(255),
    metadata JSONB,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_longmemeval_chat_session_user_id
    ON public.chat_session(user_id, updated_at DESC);

CREATE TABLE IF NOT EXISTS public.chat_message (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    session_id UUID NOT NULL REFERENCES public.chat_session(id) ON DELETE CASCADE,
    role VARCHAR(16) NOT NULL,
    content TEXT NOT NULL,
    metadata JSONB,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_longmemeval_chat_message_session_created
    ON public.chat_message(session_id, created_at DESC);

CREATE TABLE IF NOT EXISTS public.user_memory (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id VARCHAR(64) NOT NULL,
    session_id UUID,
    memory_type VARCHAR(32) NOT NULL,
    content TEXT NOT NULL,
    importance VARCHAR(16) NOT NULL DEFAULT 'medium',
    evidence_message_id UUID,
    evidence_text TEXT,
    superseded_by_memory_id UUID,
    expires_at TIMESTAMP,
    embedding VECTOR(1024),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_longmemeval_user_memory_superseded_by
        FOREIGN KEY (superseded_by_memory_id)
        REFERENCES public.user_memory(id)
        ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_longmemeval_user_memory_user_id
    ON public.user_memory(user_id);

CREATE INDEX IF NOT EXISTS idx_longmemeval_user_memory_embedding
    ON public.user_memory USING ivfflat (embedding vector_cosine_ops);

CREATE TABLE IF NOT EXISTS public.user_memory_candidate (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id VARCHAR(64) NOT NULL,
    session_id UUID NOT NULL,
    memory_type VARCHAR(32) NOT NULL,
    content TEXT NOT NULL,
    evidence TEXT NOT NULL,
    importance VARCHAR(16) NOT NULL DEFAULT 'medium',
    evidence_message_id UUID,
    status VARCHAR(16) NOT NULL DEFAULT 'PENDING',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_longmemeval_memory_candidate_status
        CHECK (status IN ('PENDING', 'PERSISTED', 'DISCARDED'))
);

CREATE INDEX IF NOT EXISTS idx_longmemeval_user_memory_candidate_user_id
    ON public.user_memory_candidate(user_id);

COMMIT;
